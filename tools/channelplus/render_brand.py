"""Generate Channel + vector assets from the bundled OFL Poppins font.

Run from any directory with Python + fontTools. Resource names stay stable so
saved icon choices and launcher aliases continue to work after an upgrade.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "owntv_core_tdt/core/src/main/res"
FONT = TTFont(ROOT / "owntv_tdt/app/src/main/res/font/poppins_bold.ttf")
GLYPHS = FONT.getGlyphSet()
CMAP = FONT.getBestCmap()

def lettering(text, x, y, size):
    scale = size / FONT['head'].unitsPerEm
    paths = []
    for char in text:
        glyph = CMAP[ord(char)]
        pen = SVGPathPen(GLYPHS)
        GLYPHS[glyph].draw(TransformPen(pen, (scale, 0, 0, -scale, x, y)))
        paths.append(pen.getCommands())
        x += FONT['hmtx'][glyph][0] * scale
    return ''.join(paths)

def path(data, color):
    return f'<path android:fillColor="{color}" android:pathData="{data}"/>'

def vector(width, height, body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Channel +. Generated by tools/channelplus/render_brand.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
            f'android:width="{width}dp" android:height="{height}dp" '
            f'android:viewportWidth="{width}" android:viewportHeight="{height}">\n{body}\n</vector>\n')

def save(name, contents, folder='drawable'):
    target = RES / folder / (name + '.xml')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(contents)

COLORS = dict(petrol='#5CC2BC', sunflower='#FFD24D', cobalt='#8AAAFF',
              tomato='#FF9C84', board='#52DBC8', eggshell='#86D3DB',
              olive='#A5CC4E', olive_cream='#A5CC4E', pixel='#52DBC8')
C = 'M67,28 A29,29 0 1,0 67,80 L59,68 A16,16 0 1,1 59,40 Z'
PLUS = 'M75,39 H85 V49 H95 V59 H85 V69 H75 V59 H65 V49 H75 Z'

def mark(accent, inset=False):
    body = path(C, '#FFF6EE') + path(PLUS, accent)
    return f'<group android:scaleX="0.66" android:scaleY="0.66" android:translateX="18" android:translateY="18">{body}</group>' if inset else body

if __name__ == '__main__':
    # Remove the raster versions: Android density qualifiers otherwise take priority.
    for pattern in ('owntv_icon_*_foreground.png', 'owntv_banner_*.png', 'owntv_splash_name_*.png'):
        for old in RES.glob('*/' + pattern):
            old.unlink()
    for name, accent in COLORS.items():
        for prefix in ('owntv_mark_', 'owntv_mark_small_'):
            save(prefix + name, vector(108, 108, mark(accent)))
        for prefix in ('owntv_splash_', 'owntv_splash_static_'):
            save(prefix + name, vector(108, 108, mark(accent, True)))
        save('owntv_icon_' + name + '_foreground', vector(108, 108, mark(accent, True)), 'mipmap-anydpi')
        title = path(lettering('Channel', 28, 105, 49), '#FFF6EE') + path(lettering('+', 251, 105, 49), accent)
        save('owntv_banner_' + name, vector(320, 180, path('M0,0 H320 V180 H0 Z', '#101A25') + title))
        save('owntv_splash_name_' + name, vector(320, 80, '<group android:translateY="-50">' + title + '</group>'))
    save('owntv_mark_play', vector(108, 108, path(PLUS, '#FFFFFF')))
    save('owntv_mark_play_small', vector(108, 108, path(PLUS, '#FFFFFF')))
    save('owntv_icon_monochrome', vector(108, 108, mark('#FFFFFF', True)))
    # Keep the existing wordmark's 988:182 aspect ratio for all layouts.
    save('owntv_wordmark_own', vector(988, 182, path(lettering('Channel', 4, 156, 174), '#FFF6EE')))
    save('owntv_wordmark_tv', vector(988, 182, path(lettering('+', 816, 156, 174), '#86D3DB')))
